import { readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const directory = join(root, 'assets/audio');
const files = (await readdir(directory)).filter((name) => /^[a-z0-9-]+(?:\.[a-z0-9-]+)+\.(m4a|mp3|wav)$/.test(name)).sort();
const entries = new Map();
for (const name of files) {
  const id = name.replace(/\.(m4a|mp3|wav)$/, '');
  if (entries.has(id)) throw new Error(`More than one audio file for ${id}`);
  entries.set(id, name);
}
const lines = [...entries].map(([id, name]) => `  ${JSON.stringify(id)}: require('../../assets/audio/${name}'),`);
await writeFile(join(root, 'src/content/audio.generated.ts'), `// Generated by scripts/build-audio-manifest.mjs. Do not edit by hand.\nexport const GENERATED_AUDIO: Record<string, number> = {\n${lines.join('\n')}${lines.length ? '\n' : ''}};\n`);
